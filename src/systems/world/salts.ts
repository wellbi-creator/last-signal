/**
 * Реестр salt для производных seed. Каждое назначение случайности в генерации мира получает
 * собственный salt: `hashInts(worldSeed, SALT.xxx, ...)`. Благодаря этому независимые части мира
 * (рельеф, влажность, слои объектов, точки интереса, тропы) не влияют друг на друга.
 *
 * ПРАВИЛА:
 * - значения не меняются и не переиспользуются: это равносильно смене алгоритма генерации;
 * - новое назначение получает новый, ещё не занятый номер;
 * - любое изменение значения после первого использования в генераторе требует
 *   нового WORLD_GEN_VERSION (см. config.ts и docs/M1_PLAN.md, раздел 7).
 *
 * Тест tests/world/salts.test.ts фиксирует эти значения и их уникальность.
 */
export const SALT = {
  /** Поле высоты рельефа. */
  ELEVATION: 1,
  /** Поле влажности. */
  MOISTURE: 2,
  /** Низкочастотное поле кластеризации объектов (поляны и чащи). */
  CLUSTER: 3,

  /** Слои расстановки объектов, в порядке приоритета (1 — выше всех). */
  LAYER_BUILDINGS: 10,
  LAYER_DEPOSITS: 11,
  LAYER_TREES: 12,
  LAYER_ROCKS: 13,
  LAYER_BUSHES: 14,

  /** Гарантированный стартовый набор объектов вокруг точки старта. */
  STARTER: 20,
  /** Выбор мест под точки интереса. */
  POI: 30,
  /** Прокладка троп. */
  TRAIL: 40,
} as const;

export type Salt = (typeof SALT)[keyof typeof SALT];
